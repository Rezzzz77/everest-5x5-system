-- ۱) جدول وضعیت کاربر
create table if not exists public.user_state (
  id         bigint generated by default as identity primary key,
  user_id    text unique not null,
  state_data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- ۲) فعال‌سازی Row Level Security
alter table public.user_state enable row level security;

-- ۳) سیاست دسترسی
--  ⚠️ توجه: این سیاست برای MVP ساده است و به anon اجازه خواندن/نوشتن می‌دهد.
--  برای محیط عملیاتی، مهاجرت به Supabase Auth و محدودسازی به auth.uid() لازم است.
--  (در فایل docs/SECURITY.md توضیح داده شده)
drop policy if exists "anon read-write user_state" on public.user_state;
create policy "anon read-write user_state"
  on public.user_state
  for all
  to anon
  using (true)
  with check (true);

-- ۴) ایندکس برای جستجوی سریع
create index if not exists idx_user_state_user_id on public.user_state (user_id);
create index if not exists idx_user_state_updated_at on public.user_state (updated_at desc);

-- ۵) تریگر به‌روزرسانی خودکار updated_at
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_user_state_touch on public.user_state;
create trigger trg_user_state_touch
  before update on public.user_state
  for each row execute function public.touch_updated_at();

