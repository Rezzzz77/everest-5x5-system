-- ============================================================
--  سیستم ۵×۵ تیم اورست — شمای امن Supabase (با Supabase Auth)
--  اجرا در: Supabase Dashboard → SQL Editor → New query → Run
--  این فایل idempotent است؛ اجرای دوباره خطا نمی‌دهد و با
--  جدول‌های موجود (حتی ساخته‌شده توسط اپ دیگر) سازگار می‌شود.
--
--  نکته مهم: در این پروژه جدول profiles از قبل وجود داشته و کلید
--  یکتای کاربر در ستون `id` است (FK به auth.users). ما همان را
--  حفظ می‌کنیم تا اپ‌های دیگرِ همین پروژه نشکنند. `user_state`
--  از ستون `user_id` استفاده می‌کند.
-- ============================================================

-- ------------------------------------------------------------
-- ۰) پاک‌سازی سیاست‌های ناامن نسخه‌های قبلی
-- ------------------------------------------------------------
do $$
begin
  if to_regclass('public.user_state') is not null then
    drop policy if exists "Users manage their own state" on public.user_state;
    drop policy if exists "anon rw" on public.user_state;
    drop policy if exists "users own their row" on public.user_state;
  end if;
end $$;

-- ------------------------------------------------------------
-- ۱) جدول وضعیت کاربر
--    user_id از Auth می‌آید و قابل جعل نیست.
-- ------------------------------------------------------------
create table if not exists public.user_state (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null unique references auth.users(id) on delete cascade,
  state_data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- اگر جدول از نسخه قبلی با user_id text مانده باشد، به uuid تبدیل شود
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'user_state'
      and column_name = 'user_id' and data_type = 'text'
  ) then
    alter table public.user_state alter column user_id type uuid using user_id::uuid;
  end if;
end $$;

-- ------------------------------------------------------------
-- ۲) پروفایل (کد ملی و نام حامی) — جدا از state عمومی
--    کلید یکتا = همان شناسه کاربر در Auth.
-- ------------------------------------------------------------
create table if not exists public.profiles (
  id            uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  full_name     text,
  national_id   text,
  upline        text,
  email         text,
  upline_email  text,
  upline_id     uuid references auth.users(id),
  current_stage int not null default 1,
  s2_streak     int not null default 0,
  crm_count     int not null default 0,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- سازگاری: اگر نسخه قدیمی این فایل جدول را با user_id ساخته باشد
do $$
begin
  if to_regclass('public.profiles') is not null
     and not exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'profiles' and column_name = 'id'
     )
     and exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'profiles' and column_name = 'user_id'
     )
  then
    alter table public.profiles rename column user_id to id;
  end if;
end $$;

-- ستون‌هایی که اپ لازم دارد (جدول موجود ممکن است آن‌ها را نداشته باشد)
alter table public.profiles add column if not exists full_name     text;
alter table public.profiles add column if not exists national_id   text;
alter table public.profiles add column if not exists upline        text;
alter table public.profiles add column if not exists email         text;
alter table public.profiles add column if not exists upline_email  text;
alter table public.profiles add column if not exists upline_id     uuid references auth.users(id);
alter table public.profiles add column if not exists current_stage int not null default 1;
alter table public.profiles add column if not exists s2_streak     int not null default 0;
alter table public.profiles add column if not exists crm_count     int not null default 0;
alter table public.profiles add column if not exists role          text not null default 'member';
alter table public.profiles add column if not exists approved_stage int not null default 1;
alter table public.profiles add column if not exists pending_stage  int;
alter table public.profiles add column if not exists created_at    timestamptz not null default now();
alter table public.profiles add column if not exists updated_at    timestamptz not null default now();

-- اجازه درج بدون فرستادن id؛ مقدار همیشه از JWT گرفته می‌شود
alter table public.profiles alter column id set default auth.uid();

-- ------------------------------------------------------------
-- ۳) تریگر updated_at (DEFAULT now() فقط هنگام INSERT کار می‌کند)
-- ------------------------------------------------------------
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_user_state_touch on public.user_state;
create trigger trg_user_state_touch
  before update on public.user_state
  for each row execute function public.touch_updated_at();

drop trigger if exists trg_profiles_touch on public.profiles;
create trigger trg_profiles_touch
  before update on public.profiles
  for each row execute function public.touch_updated_at();

-- ------------------------------------------------------------
-- ۳.۱) محافظت از ستون role در جدول profiles (در صورت وجود ستون)
-- ------------------------------------------------------------
create or replace function public.protect_profile_role()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'UPDATE' and new.role is distinct from old.role and current_user not in ('service_role', 'postgres') then
    raise exception 'تغییر نقش کاربر مجاز نیست (فقط service_role)';
  end if;
  return new;
end;
$$;

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'profiles' and column_name = 'role'
  ) then
    drop trigger if exists trg_protect_profile_role on public.profiles;
    create trigger trg_protect_profile_role
      before update on public.profiles
      for each row execute function public.protect_profile_role();
  end if;
end $$;

-- ------------------------------------------------------------
-- ۳.۲) همگام‌سازی خودکار مرحله و آمار کاربر در profiles برای مشاهده لیدر
-- ------------------------------------------------------------
create or replace function public.sync_profile_progress()
returns trigger
language plpgsql
security definer
as $$
declare
  _streak int := 0;
  _crm_cnt int := 0;
  _stage int := 1;
  _s1_done boolean := false;
  _s3_done boolean := false;
  _s4_done boolean := false;
begin
  _streak := coalesce((new.state_data->>'s2Streak')::int, 0);

  if jsonb_typeof(new.state_data->'crm') = 'array' then
    _crm_cnt := jsonb_array_length(new.state_data->'crm');
  end if;

  if jsonb_typeof(new.state_data->'s1Steps') = 'array'
     and not exists (select 1 from jsonb_array_elements(new.state_data->'s1Steps') elem where elem::text <> 'true') then
    _s1_done := true;
  end if;

  if _s1_done then
    _stage := 2;
    if _streak >= 7 then
      _stage := 3;
      if jsonb_typeof(new.state_data->'s3Pass') = 'array'
         and not exists (select 1 from jsonb_array_elements(new.state_data->'s3Pass') elem where coalesce((elem->>'done')::boolean, false) = false) then
        _stage := 4;
        if jsonb_typeof(new.state_data->'s4Pass') = 'array'
           and not exists (select 1 from jsonb_array_elements(new.state_data->'s4Pass') elem where coalesce((elem->>'done')::boolean, false) = false) then
          _stage := 5;
        end if;
      end if;
    end if;
  end if;

  update public.profiles
  set
    current_stage = _stage,
    s2_streak     = _streak,
    crm_count     = _crm_cnt,
    updated_at    = now()
  where id = new.user_id;

  return new;
end;
$$;

drop trigger if exists trg_sync_profile_progress on public.user_state;
create trigger trg_sync_profile_progress
  after insert or update on public.user_state
  for each row execute function public.sync_profile_progress();

-- ------------------------------------------------------------
-- ۳.۳) اتصال خودکار upline_id بر اساس upline_email
-- ------------------------------------------------------------
create or replace function public.link_upline()
returns trigger
language plpgsql
security definer
as $$
begin
  if new.upline_email is not null and (new.upline_id is null or (old.upline_email is distinct from new.upline_email)) then
    select id into new.upline_id
    from public.profiles
    where lower(email) = lower(new.upline_email)
    limit 1;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_link_upline on public.profiles;
create trigger trg_link_upline
  before insert or update on public.profiles
  for each row execute function public.link_upline();

-- ------------------------------------------------------------
-- ۴) Row Level Security
-- ------------------------------------------------------------
alter table public.user_state enable row level security;
alter table public.profiles   enable row level security;

drop policy if exists "users own their state" on public.user_state;
create policy "users own their state"
  on public.user_state
  for all
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- کاربر خود ردیفش را مدیریت می‌کند (CRUD کامل)
drop policy if exists "users own their profile" on public.profiles;
drop policy if exists "users can update own profile" on public.profiles;
create policy "users can update own profile"
  on public.profiles
  for all
  to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- لیدر بالاسری می‌تواند پروفایل اعضای زیرمجموعه‌اش را مشاهده کند (فقط SELECT)
drop policy if exists "leaders can view downline profiles" on public.profiles;
create policy "leaders can view downline profiles"
  on public.profiles
  for select
  to authenticated
  using (
    id = (select auth.uid())
    or upline_id = (select auth.uid())
    or (upline_email is not null and lower(upline_email) = lower(auth.jwt()->>'email'))
  );

-- ------------------------------------------------------------
-- ۵) دسترسی‌ها
--    anon: هیچ. authenticated: فقط CRUD (بدون TRUNCATE/TRIGGER/REFERENCES)
-- ------------------------------------------------------------
revoke all on public.user_state from anon;
revoke all on public.profiles   from anon;

revoke truncate, references, trigger on public.user_state from authenticated;
revoke truncate, references, trigger on public.profiles   from authenticated;

grant select, insert, update, delete on public.user_state to authenticated;
grant select, insert, update, delete on public.profiles   to authenticated;

-- ------------------------------------------------------------
-- ۵.۱) تایید خودکار کاربران جدید در auth.users (بدون نیاز به لینک تایید ایمیل)
-- ------------------------------------------------------------
create or replace function public.auto_confirm_user()
returns trigger
language plpgsql
security definer
as $$
begin
  new.email_confirmed_at = coalesce(new.email_confirmed_at, now());
  new.confirmed_at = coalesce(new.confirmed_at, now());
  return new;
end;
$$;

drop trigger if exists trg_auto_confirm_user on auth.users;
create trigger trg_auto_confirm_user
  before insert on auth.users
  for each row execute function public.auto_confirm_user();

-- ------------------------------------------------------------
-- ۵.۲) توابع تایید صلاحیت مراحل اعضا توسط راهبر
-- ------------------------------------------------------------
create or replace function public.request_stage_approval(p_target_stage int)
returns void
language plpgsql
security definer
as $$
begin
  update public.profiles
  set pending_stage = p_target_stage,
      updated_at = now()
  where id = auth.uid();
end;
$$;

create or replace function public.approve_member_stage(p_member_id uuid, p_stage int)
returns void
language plpgsql
security definer
as $$
declare
  v_caller_role text;
  v_member_upline uuid;
begin
  select role into v_caller_role from public.profiles where id = auth.uid();
  select upline_id into v_member_upline from public.profiles where id = p_member_id;

  if v_caller_role = 'leader' or v_member_upline = auth.uid() then
    update public.profiles
    set approved_stage = greatest(approved_stage, p_stage),
        pending_stage = null,
        updated_at = now()
    where id = p_member_id;
  else
    raise exception 'فقط راهبر بالاسری مجاز به تایید مرحله است.';
  end if;
end;
$$;

grant execute on function public.request_stage_approval(int) to authenticated;
grant execute on function public.approve_member_stage(uuid, int) to authenticated;

